    document.addEventListener('DOMContentLoaded', function () {
        setTimeout(function () {
            document.querySelectorAll('.dropdown-toggle.price.w-dropdown-toggle').forEach(function (toggle) {
                toggle.addEventListener('click', function (e) {
                    e.preventDefault();
                    const dropdown = toggle.closest('.dropdown.price.w-dropdown');
                    const list = dropdown.querySelector('.dropdown-list.price.w-dropdown-list');
                    if (list) {
                        if (getComputedStyle(list).display === 'none' || list.style.display === 'none') {
                            list.style.setProperty('display', 'block', 'important');
                            toggle.classList.add('open');
                            toggle.classList.remove('close');
                        } else {
                            list.style.setProperty('display', 'none', 'important');
                            toggle.classList.add('close');
                            toggle.classList.remove('open');
                        }
                    }
                });
            });
        }, 3000);
    });

    // reviews swiper
    let swiperReviews = new Swiper('[data-swiper=reviews]', {
        speed: 800,
        slidesPerView: 3,
        spaceBetween: 16,
        allowTouchMove: true,
        loop: false,
        breakpoints: {
            220: {
                slidesPerView: 1.2,
            },
            768: {
                slidesPerView: 3,
            }
        },
        on: {
            init: function () {
                let paginationItems = $('[data-swiper-reviews="pagination"]').children();
                paginationItems.find('[data-anim]').removeClass('active');
                setTimeout(() => {
                    paginationItems.eq(0).find('[data-anim]').addClass('active');
                }, 100);
            },
            slideChange: function () {
                let paginationItems = $('[data-swiper-reviews="pagination"]').children();
                let pagLength = paginationItems.length;
                let activeIndex = this.realIndex % pagLength;

                paginationItems.find('[data-anim]').removeClass('active');
                paginationItems.eq(activeIndex).find('[data-anim]').addClass('active');
            },
        },
    });

    // dropdown
    document.addEventListener("DOMContentLoaded", () => {
        document.querySelectorAll("[dropdown]").forEach(dropdown => {
            dropdown.querySelectorAll("[data-anim]").forEach(element => {
                element.classList.remove("active");
                if (element.classList.contains("dropdown-list")) {
                    element.style.height = "0px";
                }
            });
        });
    });

    document.addEventListener("click", (event) => {
        const trigger = event.target.closest("[drop-trigger]");
        if (trigger) {
            const dropdown = trigger.closest("[dropdown]");
            if (dropdown) {
                const animElements = dropdown.querySelectorAll("[data-anim]");
                if (dropdown.hasAttribute("dropdown-single")) {
                    document.querySelectorAll("[dropdown-single]").forEach(otherDropdown => {
                        if (otherDropdown !== dropdown) {
                            otherDropdown.querySelectorAll("[data-anim]").forEach(element => {
                                element.classList.remove("active");
                                if (element.classList.contains("dropdown-list")) {
                                    element.style.height = "0px";
                                }
                            });
                        }
                    });
                }
                animElements.forEach(element => {
                    if (element.classList.contains("dropdown-list")) {
                        if (element.classList.contains("active")) {
                            element.classList.remove("active");
                            element.style.height = "0px";
                        } else {
                            element.classList.add("active");
                            const naturalHeight = element.scrollHeight;
                            element.style.height = `${naturalHeight}px`;
                        }
                    } else {
                        element.classList.toggle("active");
                    }
                });
            }
        }
    });

    //dropdown animation
    document.addEventListener("DOMContentLoaded", () => {
        const dropdowns = document.querySelectorAll("[dropdown-anim]");

        const observerOptions = {
            root: null,
            rootMargin: "0px",
            threshold: 0.2
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add("visible");
                }
            });
        }, observerOptions);

        dropdowns.forEach(dropdown => {
            observer.observe(dropdown);
        });
    });

    // double dropdown anim
    document.addEventListener('DOMContentLoaded', function () {
        const dropdowns = document.querySelectorAll('.dropdown.price.w-dropdown');

        dropdowns.forEach(dropdown => {
            const toggle = dropdown.querySelector('.dropdown-toggle.price.w-dropdown-toggle');
            const list = dropdown.querySelector('.dropdown-list.price.w-dropdown-list');
            const icon = toggle?.querySelector('.dropdown-icon');

            if (toggle && list && icon) {
                const observer = new MutationObserver(() => {
                    if (list.classList.contains('w--open')) {
                        icon.style.transform = 'rotateZ(180deg)';
                    } else {
                        icon.style.transform = 'rotateZ(0deg)';
                    }
                });

                observer.observe(list, {attributes: true, attributeFilter: ['class']});
            }
        });
    });

